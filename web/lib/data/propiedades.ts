export function getPropiedadBySlug(slug: string): Propiedad | undefined {
  return propiedades.find((p) => p.slug === slug);
}

export function getPropiedadesDestacadas(): Propiedad[] {
  return propiedades.filter((p) => p.destacado);
}

export function getPropiedadesPorAgente(agenteId: string): Propiedad[] {
  return propiedades
    .filter((p) => p.agente_id === agenteId && p.disponible)
    .sort((a, b) => new Date(b.publicado_en).getTime() - new Date(a.publicado_en).getTime());
}

export function getPropiedadesSimilares(propiedad: Propiedad): Propiedad[] {
  return propiedades
    .filter((p) => p.id !== propiedad.id)
    .filter((p) => p.tipo === propiedad.tipo || p.zona === propiedad.zona)
    .slice(0, 3);
}
